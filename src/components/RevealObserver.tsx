"use client";

import { usePathname } from "next/navigation";
import { useEffect } from "react";

/**
 * Un solo IntersectionObserver per tutto il sito: gli elementi con
 * [data-reveal] ricevono .is-in quando entrano nel viewport. L'animazione
 * vera e propria è in CSS; senza JS o con movimento ridotto tutto resta
 * semplicemente visibile.
 */
export function RevealObserver() {
  const pathname = usePathname();

  useEffect(() => {
    const els = Array.from(document.querySelectorAll<HTMLElement>("[data-reveal]:not(.is-in)"));
    if (!("IntersectionObserver" in window)) {
      els.forEach((el) => el.classList.add("is-in"));
      return;
    }
    const io = new IntersectionObserver(
      (entries) => {
        for (const entry of entries) {
          if (entry.isIntersecting) {
            entry.target.classList.add("is-in");
            io.unobserve(entry.target);
          }
        }
      },
      { rootMargin: "0px 0px -8% 0px", threshold: 0.12 },
    );
    els.forEach((el) => io.observe(el));
    return () => io.disconnect();
  }, [pathname]);

  return null;
}
